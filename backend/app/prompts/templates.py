MORNING_PROMPT = """## 任务
帮用户规划今天最值得做的事，给一句让他/她想去做的话。

## 用户信息
- 昵称：{nickname}
- 连续打卡：{streak_days}天
- 今日待办任务：
{tasks_list}
- 昨日完成情况：{yesterday_summary}
- AI 对用户的了解：{ai_memory}

## 要求
1. 从待办中挑出今天最值得做的 1-3 件事，按精力排序（先难后易）
2. 给每件事一个预估时间
3. 给一句思维转换（不要鸡汤，要具体、有画面感、跟用户的任务相关）
4. 如果用户昨天有未完成的任务，温和提一下，别指责
5. 如果是连续打卡的成就节点（7天、30天、100天），祝贺一下
6. 控制在 200 字以内
7. 用 markdown 格式，方便前端渲染

## 输出格式示例
早上好！[个性化问候]

今天建议这样安排：
1. 🎯 [任务名] （约X分钟）
2. 📚 [任务名] （约X分钟）

💡 [一句思维转换]

[简短鼓励，不要鸡汤]
"""

